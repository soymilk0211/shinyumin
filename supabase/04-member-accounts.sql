-- ============================================================
-- 御茗有限公司 電商網站 — 會員功能：把訂單接到帳號上
-- ============================================================
-- 使用方式：整份複製，貼到 Supabase Dashboard 的 SQL Editor，按 Run。
-- 這份 SQL 可以重複執行，跑第二次不會弄壞任何東西。
--
-- 【這份 SQL 只做一件事：在訂單表加一個欄位。】
--
-- 為什麼需要它：會員登入之後要看到「我的訂單」，
-- 資料庫得知道「這張訂單是誰的」。現在的訂單只存了姓名與電話，
-- 那是【寫在訂單上的聯絡資料】，不是帳號 —— 兩張訂單留一樣的電話，
-- 資料庫也不知道那是同一個人。
--
-- 所以加一個 user_id，把訂單指到登入的帳號上。就這樣，沒有別的。
-- ============================================================


-- ------------------------------------------------------------
-- 訂單加上「這是誰下的」
-- ------------------------------------------------------------
-- 可以是空的（null）：【不登入也能買】是刻意保留的設計，
-- 訪客下的單就沒有 user_id。
--
-- on delete set null 的意思是：客人日後把帳號刪掉時，
-- 訂單【不會跟著消失】，只是不再屬於任何帳號。
-- 訂單的金額與品項是帳務憑證，不能因為刪帳號就跟著不見。
alter table public.orders
  add column if not exists user_id uuid
  references auth.users(id) on delete set null;

create index if not exists orders_user_id_idx on public.orders (user_id);

comment on column public.orders.user_id is
  '下單的會員帳號。訪客結帳時為 null —— 不登入也能買是刻意的設計。'
  ' 客人刪除帳號時這裡會變回 null，訂單本身保留。';


-- ------------------------------------------------------------
-- 門禁維持原樣：訂單對訪客仍然完全鎖死
-- ------------------------------------------------------------
-- 【這裡刻意不開放「會員用自己的鑰匙讀自己的訂單」。】
--
-- Supabase 的標準做法是加一條 RLS 政策讓 user_id = auth.uid() 的人讀得到。
-- 我們不那樣做，因為這個網站從第一天起就是「訂單一律走伺服器端」：
-- 網站後端先確認登入狀態，再用 service_role 去查。
--
-- 好處是訂單表對瀏覽器端的那把公開金鑰【永遠是關著的】，
-- 少一條政策就少一個寫錯會外洩個資的地方。
--
-- 所以這份 SQL 不新增任何 policy。


-- ------------------------------------------------------------
-- 確認結果
-- ------------------------------------------------------------
-- 跑完會印出剛加好的欄位，看到 user_id 就是成功了。
select
  column_name  as "欄位",
  data_type    as "型別",
  is_nullable  as "可以留空嗎"
from information_schema.columns
where table_schema = 'public'
  and table_name = 'orders'
  and column_name = 'user_id';
